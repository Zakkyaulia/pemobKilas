/// Centralized spacing constants for the KILAS app.
///
/// Use these instead of arbitrary numeric values for padding,
/// margins, and gaps to maintain visual consistency.
abstract final class AppSpacing {
  /// 4.0 — micro spacing, icon inner padding.
  static const double xs = 4.0;

  /// 8.0 — small gaps between related elements.
  static const double sm = 8.0;

  /// 12.0 — medium gaps, form field internal spacing.
  static const double md = 12.0;

  /// 16.0 — standard section padding, card padding.
  static const double lg = 16.0;

  /// 20.0 — larger gaps between sections.
  static const double xl = 20.0;

  /// 24.0 — section separators, card content padding.
  static const double xxl = 24.0;

  /// 32.0 — major section breaks.
  static const double xxxl = 32.0;

  /// 40.0 — screen top/bottom margins.
  static const double xxxxl = 40.0;

  /// 48.0 — extra large spacing.
  static const double xxxxxl = 48.0;
}
